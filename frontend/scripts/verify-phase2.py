"""Browser acceptance checks. Uses an isolated browser context, never user data."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'outputs'
OUT.mkdir(exist_ok=True)
URL = 'http://127.0.0.1:5173'
checks = []
errors = []

def done(name):
    checks.append(name)
    print('PASS:', name, flush=True)

with sync_playwright() as p:
    executable = Path.home() / 'AppData/Local/ms-playwright/chromium_headless_shell-1208/chrome-headless-shell-win64/chrome-headless-shell.exe'
    browser = p.chromium.launch(executable_path=str(executable), headless=True)
    context = browser.new_context(viewport={'width': 1440, 'height': 1000}, locale='zh-CN')
    page = context.new_page()
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(URL, wait_until='networkidle')
    expect(page.get_by_role('heading', name='台账已准备好，开始登记第一份档案')).to_be_visible()
    done('Initial source contains no invented archive records')
    page.get_by_role('button', name='载入演示数据', exact=True).first.click()
    expect(page.locator('.ledger-table tbody tr')).to_have_count(10)
    page.get_by_role('button', name='下一页', exact=True).click()
    expect(page.locator('.ledger-table tbody tr')).to_have_count(3)
    page.get_by_placeholder('档案名称 / 证书编号').fill('演示13')
    page.get_by_role('button', name='查询', exact=True).click()
    expect(page.locator('.ledger-table tbody tr')).to_have_count(1)
    done('Demo data marked; pagination, search and page reset work')
    page.get_by_role('button', name='详情', exact=True).click()
    expect(page.get_by_role('dialog')).to_be_visible()
    expect(page.get_by_role('dialog').get_by_text('待核定（字典待补）', exact=True)).to_be_visible()
    page.get_by_role('button', name='编辑草稿', exact=True).click()
    page.get_by_label('档案名称', exact=False).fill('页面验收修改 · 演示')
    page.get_by_role('button', name='保存草稿', exact=True).first.click()
    page.reload(wait_until='networkidle')
    page.get_by_placeholder('档案名称 / 证书编号').fill('页面验收修改')
    page.get_by_role('button', name='查询', exact=True).click()
    expect(page.locator('.ledger-table tbody tr')).to_have_count(1)
    done('Details, edit and browser persistence work')
    page.get_by_role('button', name='新增档案', exact=True).click()
    page.get_by_label('档案大类', exact=False).select_option('qualification')
    expect(page.get_by_label('二级分类', exact=False)).to_have_count(0)
    page.get_by_label('证件名称', exact=False).fill('验收证照草稿')
    page.get_by_label('证书编号', exact=False).fill('00123')
    page.get_by_label('原件数量', exact=False).fill('0')
    page.get_by_label('证件有效期', exact=False).select_option('fixed')
    page.get_by_label('有效开始日期', exact=False).fill('2026-12-31')
    page.get_by_label('有效到期日期', exact=False).fill('2026-01-01')
    page.get_by_role('button', name='保存草稿', exact=True).first.click()
    expect(page.get_by_text('有效开始日期不得晚于到期日期。', exact=True)).to_be_visible()
    page.get_by_label('证件有效期', exact=False).select_option('permanent')
    page.get_by_role('button', name='保存草稿', exact=True).first.click()
    page.get_by_role('button', name='详情', exact=True).first.click()
    dialog = page.get_by_role('dialog')
    expect(dialog.get_by_text('00123', exact=True)).to_be_visible()
    expect(dialog.get_by_text('长期有效', exact=True)).to_be_visible()
    expect(dialog.locator('dd').filter(has_text='待核实').first).to_be_visible()
    page.get_by_role('button', name='关闭', exact=True).click()
    done('Conditional fields, date-order validation, leading zero, blank and zero preserved')
    page.get_by_role('button', name='新增档案', exact=True).click()
    page.get_by_label('档案大类', exact=False).select_option('document')
    page.get_by_label('二级分类', exact=False).select_option('cat-09')
    page.get_by_label('三级分类', exact=False).select_option('cat-09-01')
    page.get_by_label('下级分类', exact=False).select_option('cat-09-01-02')
    expect(page.get_by_label('下级分类', exact=False)).to_have_value('cat-09-01-02')
    page.get_by_label('所属公司', exact=False).select_option('company-5')
    expect(page.get_by_label('二级分类', exact=False)).to_have_count(0)
    expect(page.get_by_text('该公司尚未启用文书目录，请先在“公司与部门”中确认适用范围。')).to_be_visible()
    page.get_by_label('所属公司', exact=False).select_option('company-4')
    page.get_by_label('二级分类', exact=False).select_option('cat-20')
    page.get_by_label('档案名称', exact=False).fill('年份验证')
    page.get_by_role('button', name='保存草稿', exact=True).first.click()
    expect(page.get_by_text('请填写四位编号年份；年份用途待业务最终确认。', exact=True)).to_be_visible()
    page.get_by_label('编号年份', exact=False).fill('2026')
    page.get_by_role('button', name='保存草稿', exact=True).first.click()
    expect(page.get_by_role('heading', name='档案台账', exact=True)).to_be_visible()
    done('Deep classification, company cascade reset, directory scope and year validation')
    page.get_by_role('button', name='公司与部门', exact=True).click()
    expect(page.locator('tbody tr')).to_have_count(33)
    page.get_by_role('button', name='新增公司', exact=True).click()
    page.get_by_label('公司全称', exact=False).fill('验收测试公司')
    page.get_by_label('公司编码', exact=False).fill('GF')
    page.get_by_role('button', name='保存公司', exact=True).click()
    expect(page.get_by_text('公司编码已存在，请使用唯一编码。', exact=True)).to_be_visible()
    page.get_by_label('公司编码', exact=False).fill('QA')
    page.get_by_label('公司简称', exact=False).fill('验收公司')
    page.get_by_label('已确认适用当前文书目录', exact=False).check()
    page.get_by_role('button', name='保存公司', exact=True).click()
    expect(page.locator('tbody tr')).to_have_count(34)
    page.get_by_role('tab', name='部门目录', exact=True).click()
    page.get_by_role('button', name='新增部门', exact=True).click()
    qa_company = page.get_by_role('dialog').get_by_label('所属公司', exact=False).locator('option').filter(has_text='验收测试公司').get_attribute('value')
    page.get_by_role('dialog').get_by_label('所属公司', exact=False).select_option(qa_company)
    page.get_by_label('部门名称', exact=False).fill('验收部门')
    page.get_by_role('button', name='保存部门', exact=True).click()
    expect(page.get_by_text('验收部门', exact=True)).to_be_visible()
    done('Company maintenance, duplicate-code prevention, explicit scope and department maintenance')
    page.get_by_role('button', name='分类与编码', exact=True).click()
    expect(page.locator('tbody tr')).to_have_count(54)
    page.get_by_role('button', name='新增分类', exact=True).click()
    page.get_by_label('上级分类', exact=False).select_option('cat-01')
    page.get_by_label('分类编码', exact=False).fill('10')
    page.get_by_label('分类名称', exact=False).fill('验收子分类')
    page.get_by_role('button', name='保存分类', exact=True).click()
    expect(page.locator('tbody tr').filter(has_text='验收子分类')).to_have_count(1)
    page.get_by_role('button', name='档案台账', exact=True).click()
    page.get_by_role('button', name='重置', exact=True).click()
    page.screenshot(path=str(OUT/'phase2-ledger-desktop.png'), full_page=True)
    page.set_viewport_size({'width': 390, 'height': 844})
    expect(page.get_by_role('heading', name='档案台账', exact=True)).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Page overflows mobile viewport'
    page.screenshot(path=str(OUT/'phase2-ledger-mobile.png'), full_page=True)
    page.set_viewport_size({'width': 320, 'height': 720})
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Page overflows 320px viewport'
    page.set_viewport_size({'width': 1440, 'height': 1000})
    page.get_by_role('button', name='新增档案', exact=True).click()
    page.screenshot(path=str(OUT/'phase2-record-form.png'), full_page=True)
    done('Category maintenance and desktop/mobile layouts')
    other_context = browser.new_context(viewport={'width': 1280, 'height': 900})
    other = other_context.new_page()
    other.goto(URL, wait_until='networkidle')
    expect(other.get_by_role('heading', name='档案台账', exact=True)).to_be_visible()
    other.evaluate("localStorage.setItem('wansheng.archive.phase2.v1', '{broken')")
    other.reload(wait_until='networkidle')
    expect(other.get_by_role('heading', name='暂时无法打开工作区')).to_be_visible()
    assert other.evaluate("localStorage.getItem('wansheng.archive.phase2.v1')") == '{broken'
    other_context.close()
    done('Invalid browser data is preserved without silent overwrite')
    assert not errors, errors
    done('No browser runtime errors')
    # Capture clean demo-only views, separate from the acceptance-test records.
    preview_context = browser.new_context(viewport={'width': 1440, 'height': 1000}, locale='zh-CN')
    preview = preview_context.new_page()
    preview.goto(URL, wait_until='networkidle')
    expect(preview.get_by_role('heading', name='档案台账', exact=True)).to_be_visible()
    preview.screenshot(path=str(OUT/'phase2-ledger-empty.png'), full_page=True)
    preview.get_by_role('button', name='载入演示数据', exact=True).first.click()
    expect(preview.locator('.ledger-table tbody tr')).to_have_count(10)
    preview.get_by_role('button', name='关闭提示').click()
    preview.screenshot(path=str(OUT/'phase2-ledger-desktop.png'), full_page=True)
    preview.set_viewport_size({'width': 390, 'height': 844})
    preview.screenshot(path=str(OUT/'phase2-ledger-mobile.png'), full_page=True)
    preview.set_viewport_size({'width': 1440, 'height': 1000})
    preview.get_by_role('button', name='新增档案', exact=True).click()
    preview.screenshot(path=str(OUT/'phase2-record-form.png'), full_page=True)
    preview_context.close()
    browser.close()

(OUT/'phase2-browser-checks.json').write_text(json.dumps({'passed': checks, 'runtime_errors': errors, 'test_data': 'isolated browser context only'}, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps({'passed_count': len(checks), 'runtime_errors': errors}, ensure_ascii=False), flush=True)
